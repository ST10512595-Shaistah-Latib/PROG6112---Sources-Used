    private void jMenuItem2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jMenuItem2ActionPerformed
        EventTickets ticket = new EventTickets();
        price = Double.parseDouble(TxtPrice.getText());
        tickets = Integer.parseInt(TxtTickets.getText());
        event = EventBox.getSelectedItem().toString();
        double total = ticket.CalculateTicketPrice(price, tickets);
        boolean validate = ticket.ValidateData(event, price, tickets);
        TxtReport.setText("Event: " + event + "\n" +
                          "Price per Ticket: " + price + "\n" +
                          "Number of Tickets: " + tickets + "\n" +
                           "Total Price: R" + total);
        
    }//GEN-LAST:event_jMenuItem2ActionPerformed

