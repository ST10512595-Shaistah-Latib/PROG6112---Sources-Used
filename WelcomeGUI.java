    private void ReportItemActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ReportItemActionPerformed
        EstateAgent agent = new EstateAgent();
        name = TxtName.getText();
        surname = TxtSurname.getText();
        price = Double.parseDouble(TxtPropPrice.getText());
        percentage = Double.parseDouble(TxtPercent.getText());
        location = LocationBox.getSelectedItem().toString();
        commission = agent.CalculateCommission(price, percentage);
        
        
        JOptionPane.showMessageDialog(this, "Name: " + name + "\n" +
                                            "Surname: " + surname + "\n" +
                                            "Estate Agent Location: " + location + "\n" +
                                            "Commission percentage: "+ percentage + "%\n" +
                                            "Commission Earned: R" + commission);        // TODO add your handling code here:
    }//GEN-LAST:event_ReportItemActionPerformed

