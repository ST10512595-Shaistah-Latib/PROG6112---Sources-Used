    private void ReportBttnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ReportBttnActionPerformed
        name = TxtName.getText();
        surname = TxtSurname.getText();
        price = Double.parseDouble(TxtPropPrice.getText());
        percentage = Double.parseDouble(TxtPercent.getText());
        location = LocationBox.getSelectedItem().toString();
        commission = price * (percentage/100);
        
       TxtReport.setText("Name: " + name + "\n" +
                                            "Surname: " + surname + "\n" +
                                            "Esate Agent Location: " + location + "\n" +
                                            "Commission percentage: "+ percentage + "%\n" +
                                            "Commission Earned: R" + commission);
    }//GEN-LAST:event_ReportBttnActionPerformed

